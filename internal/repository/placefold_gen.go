//go:build ignore

// placefold_gen writes placefold_table.go, the case fold PlaceKey applies
// (ADR-009 §1, step 4): each code point maps to the representative of its
// unicode.SimpleFold orbit, which is the orbit's smallest lowercase letter
// (unicode.IsLower), or its smallest code point when it has none. Only the code
// points that change are listed.
//
// The table is pinned, so a Go upgrade cannot change a place key. Run it with
// the Go toolchain go.mod names (go run placefold_gen.go). If the output
// differs from the committed table, that is a change to the matching rule:
// place IDs derive from it, so it needs the re-keying ADR PL-003 requires.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"unicode"
)

func main() {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by placefold_gen.go from Unicode %s; DO NOT EDIT.\n\n", unicode.Version)
	b.WriteString("package repository\n\n")
	b.WriteString("// placeFoldUnicodeVersion is the Unicode version placeFoldTable was generated from.\n")
	fmt.Fprintf(&b, "const placeFoldUnicodeVersion = %q\n\n", unicode.Version)
	b.WriteString("// placeFoldTable maps each code point whose fold changes it to its fold,\n")
	b.WriteString("// sorted by code point. See placefold_gen.go.\n")
	b.WriteString("var placeFoldTable = [...][2]rune{\n")
	n := 0
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if f := orbitRepresentative(r); f != r {
			fmt.Fprintf(&b, "{%#04x, %#04x},", r, f)
			n++
			if n%4 == 0 {
				b.WriteString("\n")
			}
		}
	}
	b.WriteString("\n}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("placefold_table.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}

// orbitRepresentative is the fold of r by the rule above.
func orbitRepresentative(r rune) rune {
	best, bestLower := r, unicode.IsLower(r)
	for f := unicode.SimpleFold(r); f != r; f = unicode.SimpleFold(f) {
		if lower := unicode.IsLower(f); lower && !bestLower || lower == bestLower && f < best {
			best, bestLower = f, lower
		}
	}
	return best
}
