// TestPlaceKey pins every row of the vector table in ADR-009 §1, plus the
// positional key beside each. The key is frozen once place events exist
// (PL-003), so a failing row is a rule change, not a test to update.
func TestPlaceKey(t *testing.T) {
	tests := []struct{ in, key, positional string }{
		{"Boston, MA", "boston,ma", "boston,ma"},
		{" BOSTON ,ma ", "boston,ma", "boston,ma"},
		{"Boston,MA", "boston,ma", "boston,ma"},
		{"Boston MA", "boston ma", "boston ma"},
		{"New  York, NY", "new  york,ny", "new  york,ny"},
		{"New York, NY", "new york,ny", "new york,ny"},
		{"Köln, Germany", "köln,germany", "köln,germany"},
		{"Koln, Germany", "koln,germany", "koln,germany"},
		{"Straße 1, Wien", "straße 1,wien", "straße 1,wien"},
		{"Strasse 1, Wien", "strasse 1,wien", "strasse 1,wien"},
		{"Darmstadt,,,Germany", "darmstadt,germany", "darmstadt,,,germany"},
		{"Darmstadt, Germany", "darmstadt,germany", "darmstadt,germany"},
		{", , Utah, USA", "utah,usa", ",,utah,usa"},
		{"Utah, USA", "utah,usa", "utah,usa"},
		{"Boston,", "boston", "boston,"},
		{"Boston,,", "boston", "boston,,"},
		{"Boston", "boston", "boston"},
		{"Kiel", "kiel", "kiel"}, // Kelvin sign
		{"Kiel", "kiel", "kiel"},
		{"ΣΟΣ", "ςος", "ςος"},
		{"σος", "ςος", "ςος"},
		{"İzmir", "İzmir", "İzmir"},
		{"Izmir", "izmir", "izmir"},
		{"ǅakovo", "ǆakovo", "ǆakovo"},
		{"Ǆakovo", "ǆakovo", "ǆakovo"},
		{"ǆakovo", "ǆakovo", "ǆakovo"},
		// Text whose parts are all empty has no key.
		{"", "", ""},
		{",", "", ""},
		{" , , ", "", ""},
		// Every white space unicode.IsSpace reports is trimmed, not only " ".
		{"\tBoston ,\nMA ", "boston,ma", "boston,ma"},
	}
	for _, tt := range tests {
		if got := PlaceKey(tt.in); got != tt.key {
			t.Errorf("PlaceKey(%q) = %q, want %q", tt.in, got, tt.key)
		}
		if got := PositionalPlaceKey(tt.in); got != tt.positional {
			t.Errorf("PositionalPlaceKey(%q) = %q, want %q", tt.in, got, tt.positional)
		}
	}
}

// placeFoldChecksum is the SHA-256 of foldRune over every code point, each
// result written as a little-endian uint32 in code point order. It pins step 4
// of PlaceKey for the whole range: a change to placeFoldTable (such as
// regenerating it with a Go whose Unicode tables differ) fails
// TestPlaceKeyFoldTable and needs the re-keying ADR PL-003 requires.
const placeFoldChecksum = "860c403ec491875ea48bb40163ab326bdc078df2e66769feb65a167b93f2479d"

func TestPlaceKeyFoldTable(t *testing.T) {
	h := sha256.New()
	var buf [4]byte
	for r := rune(0); r <= unicode.MaxRune; r++ {
		binary.LittleEndian.PutUint32(buf[:], uint32(foldRune(r)))
		h.Write(buf[:])
	}
	if got := hex.EncodeToString(h.Sum(nil)); got != placeFoldChecksum {
		t.Errorf("fold table checksum = %s, want %s: the place matching rule changed (PL-003)", got, placeFoldChecksum)
	}
}

// TestPlaceKeyFoldTable_MatchesRule checks the pinned table against the rule it
// was generated by, on a Go whose Unicode version is the table's.
func TestPlaceKeyFoldTable_MatchesRule(t *testing.T) {
	if unicode.Version != placeFoldUnicodeVersion {
		t.Skipf("Go has Unicode %s; the fold table is Unicode %s", unicode.Version, placeFoldUnicodeVersion)
	}
	for r := rune(0); r <= unicode.MaxRune; r++ {
		best, bestLower := r, unicode.IsLower(r)
		for f := unicode.SimpleFold(r); f != r; f = unicode.SimpleFold(f) {
			if lower := unicode.IsLower(f); lower && !bestLower || lower == bestLower && f < best {
				best, bestLower = f, lower
			}
		}
		if got := foldRune(r); got != best {
			t.Fatalf("foldRune(%U) = %U, want %U", r, got, best)
		}
	}
}

